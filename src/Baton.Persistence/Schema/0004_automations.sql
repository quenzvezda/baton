-- AutomationsAndRunLifecycle.

-- Soft delete; names are unique among automations not deleted (design.md decision 5).
ALTER TABLE automations ADD COLUMN deleted_at timestamptz;
ALTER TABLE automations DROP CONSTRAINT automations_name_key;
CREATE UNIQUE INDEX automations_name_key ON automations (name) WHERE deleted_at IS NULL;

-- The secret encrypted with Data Protection, not a hash: an HMAC needs the secret (ADR-0015).
ALTER TABLE automation_triggers RENAME COLUMN webhook_secret_hash TO webhook_secret;

CREATE TABLE data_protection_keys (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  friendly_name text,
  xml           text
);

ALTER TABLE workflow_runs
  ADD COLUMN limit_keys      text[] NOT NULL DEFAULT '{}', -- limits admission must reserve, fixed at creation
  ADD COLUMN required_labels text[] NOT NULL DEFAULT '{}', -- the automation's labels when the run was created
  ADD COLUMN run_timeout     interval,                     -- deadline_at = started_at + run_timeout (AUT-09)
  ADD COLUMN cancel_reason   text CHECK (cancel_reason IN ('user','replaced','timeout')),
  ADD COLUMN blocked_on      text;                         -- limit key a Pending run last waited for

-- When cancellation was requested; the reaper closes the task 30 s later (design.md decision 6).
ALTER TABLE task_runs ADD COLUMN cancel_requested_at timestamptz;
